// Builds userscript/proto23-mod.user.js: the whole mod as a userscript for
// Tampermonkey or Violentmonkey, so it runs on the author's hosted game at
// https://23html.github.io/ with no local copy.
//
//   node tools/build-userscript.mjs            write it
//   node tools/build-userscript.mjs --check    exit 1 if the committed file is stale
//
// How it runs. Locally mod.js is the last <script> on the page, so it shares the
// game's global scope and loads before the window 'load' listener reads the
// save. A userscript manager wraps its script in a function, which would make
// every `var` and `function` in mod.js local -- the console commands, and
// everything the game reaches by name, would vanish. So the userscript does
// not run the mod itself: at document-end (DOMContentLoaded, after the game's
// inline script and before 'load') it appends mod.js to the page as an inline
// <script>, which runs in the page's own global scope exactly as the tag does.
//
// It is marked data-p23-mod, so the parts of the mod that read the game's own
// source out of document.scripts skip it. The mod's changelog is embedded too:
// the author's site has no changelog/mod-changelog.html beside the page.
//
// If the page already has the mod (a local copy, or a fork serving mod.js)
// the userscript does nothing.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(ROOT, 'userscript', 'proto23-mod.user.js');
const REPO = 'https://github.com/Xeus24/23html.github.io';
const RAW = 'https://raw.githubusercontent.com/Xeus24/23html.github.io/main/userscript/proto23-mod.user.js';

export function buildUserscript() {
  const mod = readFileSync(join(ROOT, 'mod.js'), 'utf8');
  const changelog = readFileSync(join(ROOT, 'changelog', 'mod-changelog.html'), 'utf8');
  const game = readFileSync(join(ROOT, 'index.html'), 'utf8');
  const version = (mod.match(/version:\s*'([^']+)'/) || [])[1];
  const gameVer = Number((game.match(/global\.ver=(\d+)/) || [])[1]);
  if (!version || !gameVer) throw new Error('could not read MOD.version or global.ver');

  return `// ==UserScript==
// @name         proto23 mod
// @namespace    ${REPO}
// @version      ${version}
// @description  The proto23 mod (${version}), on the author's hosted game. Backs up your save before it first runs.
// @author       Xeus24
// @homepageURL  ${REPO}
// @downloadURL  ${RAW}
// @updateURL    ${RAW}
// @match        https://23html.github.io/
// @match        https://23html.github.io/index.html
// @run-at       document-end
// @grant        none
// ==/UserScript==

// GENERATED by tools/build-userscript.mjs from mod.js and
// changelog/mod-changelog.html. Do not edit; rebuild.

(function () {
  'use strict';
  var BUILT_FOR = ${gameVer};   // the author's global.ver this build was tested against

  if (typeof window.MOD !== 'undefined') return;                // the page has the mod already
  if (typeof window.global !== 'object' || typeof window.you !== 'object') return;   // not the game

  if (window.global.ver !== BUILT_FOR) {
    console.warn('[proto23 mod] built for game v' + BUILT_FOR + ', this is v' + window.global.ver +
                 '. Loading anyway; your save is backed up first (modBackups()).');
  }

  // read by mod.js section 48, which says so in the game when the versions differ
  window.MOD_USERSCRIPT = { builtFor: BUILT_FOR, version: ${JSON.stringify(version)} };
  window.MOD_CHANGELOG_HTML = ${JSON.stringify(changelog)};

  var s = document.createElement('script');
  s.setAttribute('data-p23-mod', ${JSON.stringify(version)});
  s.textContent = ${JSON.stringify(mod + '\n//# sourceURL=proto23-mod.js\n')};
  (document.body || document.documentElement).appendChild(s);
})();
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = buildUserscript();
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT, 'utf8'); } catch (e) {}
    if (have !== text) {
      console.error('userscript/proto23-mod.user.js is out of date: run npm run build:userscript');
      process.exit(1);
    }
    console.log('userscript is up to date');
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT} (${(text.length / 1024).toFixed(0)} KB)`);
  }
}
